'''Посунь весь ігровий цикл на другий рівень - тобто tab  1раз
Щоб додати спеціальний 'менеджера контексту', який стежить за мікрофоном 👉 “включити мікрофон і почати слухати звук”
Аргементи:
1. samplerate - скільки разів в секунду ми “слухаємо” звук - fs
2. channels=1 👉 кількість каналів 1 → моно (один мікрофон)  2 → стерео (два канали)
3. blocksize=block 👉 розмір шматка звуку
4. callback=audio_cb 👉 функція, яка обробляє звук 👉 кожен раз, коли приходить звук → викликається'''
