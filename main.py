'''Імпортуємо модулі для роботи зі звуками та роботиз числами'''
import sounddevice as sd
import numpy as nm

'''Стоври глобальні змінні'''
'''1. частота дискретизації мікрофона (fs = 16000)
👉 Це скільки разів на секунду комп’ютер “знімає” звук'''
fs = 16000
'''2. Розмір блоку аудіо (скільки семплів обробляється за раз)
👉 Це скільки “шматочків звуку” комп’ютер бере за один раз'''
blocks = 256
'''3. Поточний рівень гучності
👉 Це просто - наскільки зараз гучний звукю 0 - тиша, 0.05 - голосно'''
mic_level = 0.0
'''поріг гучності мікрофона, після якого буде стрибок - 0.01. 
        Просто:
            якщо ти тихо говориш → нічого не буде
            якщо голосніше за 0.01 → пташка стрибає'''
TRESH = 0.004    
'''мпульс (швидкість вгору)
👉 Це сила стрибка вгору'''
IMPULSE = 0 


'''Напиши функцію-обробник мікрофона - 
Вона автоматично викликається, коли приходить звук 
Аргументи функції:
 1.indata - 👉 сам звук (масив чисел)
 2. frames - 👉 скільки шматочків звуку прийшло (зазвичай = block)
 3. time - 👉 інформація про час (майже не використовується)
 4. status - 👉 чи є помилка, якщо ок → пусто, якщо щось не так → там буде значення'''
def audio(indata, frames, time, status):
    '''беремо глобальну змінну - Поточний рівень гучності (щоб змінювати її)'''
    global mic_level
    '''якщо є помилка → просто пропускаємо звук'''
    if status:
        return
    '''рахуємо гучність звуку. Просто:
        підносимо до квадрату сам звук(indata)
        беремо середнє - nm.mean
        корінь - nm.sqrt
        👉 отримуємо ДРОБОВЕ число = гучність '''
    rm = (float(nm.mean(indata**2)))
    '''згладжування звуку. Просто:
        90% старого значення рівня гучності - mic_level
        10% нового рівня гучності - rms
        додати значення - отримаємо новий рівень гучності '''
    '''запам'ятовуємо новий рівень гучності в глобальну змінну'''
    mic_level = 0.9 * mic_level + 0.1 * rm
